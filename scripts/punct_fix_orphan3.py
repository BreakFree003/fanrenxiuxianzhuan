MISSING = []
applied = 0
for fname, old, new in FIXES:
    p = CH / f"{fname}.json"
    j = json.loads(p.read_text(encoding="utf-8"))
    t = j["txt"]
    if old not in t:
        MISSING.append((fname, old))
        continue
    cnt = t.count(old)
    if cnt > 1:
        print(f"WARN {fname}: '{old[:20]}' 出现 {cnt} 次, 全部替换")
    t = t.replace(old, new)
    j["txt"] = t
    p.write_text(json.dumps(j, ensure_ascii=False, indent=2), encoding="utf-8")
    applied += 1

print(f"已应用 {applied}/{len(FIXES)} 处")
if MISSING:
    print("未找到:")
    for f, o in MISSING:
        print(f"  [{f}] {o[:40]}")
