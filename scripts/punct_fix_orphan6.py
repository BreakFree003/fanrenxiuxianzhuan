#!/usr/bin/env python3
"""punct_fix_orphan6.py - 20 处连锁反应孤立引号精确修复

人工甄别后的精确替换:
- 补“: 话开始缺左引号 (。” → 。“ 或叙述后接话)
- 删”: 叙述后多余右引号
"""

import json
from pathlib import Path

DATA = Path(__file__).parent.parent / "data"
CH = DATA / "chapters_fixed"

FIXES = [
    # 补 “ (话开始)
    ("1442", "传了出来。”谁这么大胆", "传了出来。“谁这么大胆"),
    ("1784", "吩咐一声。好的，石兄！", "吩咐一声。“好的，石兄！"),
    ("1052", "记忆都没有。”圭灵也露出", "记忆都没有。“圭灵也露出"),
    ("1995", "解释起来。嗯，这倒也是。", "解释起来。“嗯，这倒也是。"),
    ("0721", "好奇的问道。”这是我一次", "好奇的问道。“这是我一次"),
    ("0536", "亲昵的样子。范夫人！", "亲昵的样子。“范夫人！"),
    ("1516", "⏎你们是人族之人！", "⏎“你们是人族之人！"),
    ("1605", "神色肃然了起来。”想来不少道友", "神色肃然了起来。“想来不少道友"),
    (
        "1610",
        "所待的屋子再无声音传出。三亿一千万！",
        "所待的屋子再无声音传出。“三亿一千万！",
    ),
    (
        "0797",
        "端坐椅上。韩兄，你是何时返回的天南。",
        "端坐椅上。“韩兄，你是何时返回的天南。",
    ),
    ("2031", "没有真动手起来。”嘿嘿，我看二位", "没有真动手起来。“嘿嘿，我看二位"),
    (
        "0684",
        "分出一只递给了此女。多谢公子赏赐！",
        "分出一只递给了此女。“多谢公子赏赐！",
    ),
    ("1972", "银发女子。”拜见敖啸前辈", "银发女子。“拜见敖啸前辈"),
    # 删 ” (叙述后多余)
    ("1209", "顿时惊呼起来。”韩立目光一闪", "顿时惊呼起来。韩立目光一闪"),
    ("2088", "羽衣少女这才有些恍然了。”⏎另一边处", "羽衣少女这才有些恍然了。⏎另一边处"),
    ("0670", "韩立真有点意外了。”⏎“不错。", "韩立真有点意外了。⏎“不错。"),
    ("1285", "就要冲下方出手。”⏎“算了吧！汪兄", "就要冲下方出手。⏎“算了吧！汪兄"),
    (
        "1420",
        "金悦却毫不在意此事。”“看来是我二人多虑了",
        "金悦却毫不在意此事。“看来是我二人多虑了",
    ),
    (
        "2455",
        "人数之多可想而知了。”高升似乎对这些凡人颇不以为然。”“原来如此",
        "人数之多可想而知了。”高升似乎对这些凡人颇不以为然。“原来如此",
    ),
]

MISSING = []
applied = 0
for fname, old, new in FIXES:
    p = CH / f"{fname}.json"
    j = json.loads(p.read_text(encoding="utf-8"))
    t = j["txt"]
    if old not in t:
        MISSING.append((fname, old))
        continue
    cnt = t.count(old)
    if cnt > 1:
        print(f"WARN {fname}: '{old[:20]}' 出现 {cnt} 次, 全部替换")
    j["txt"] = t.replace(old, new)
    p.write_text(json.dumps(j, ensure_ascii=False, indent=2), encoding="utf-8")
    applied += 1

print(f"已应用 {applied}/{len(FIXES)} 处")
if MISSING:
    print("未找到:")
    for f, o in MISSING:
        print(f"  [{f}] {o[:40]}")
